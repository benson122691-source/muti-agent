def main() -> None:
    with (HERE / "train_seed.jsonl").open("w", encoding="utf-8") as f:
        for text in SCAM:
            f.write(json.dumps({"text": text, "is_scam": True}, ensure_ascii=False) + "\n")
        for text in NORMAL:
            f.write(json.dumps({"text": text, "is_scam": False}, ensure_ascii=False) + "\n")

    with (HERE / "cases_seed.jsonl").open("w", encoding="utf-8") as f:
        for text, scam_type in CASES:
            row = {"text": text, "scam_type": scam_type, "source": "165 宣導手法整理（合成範例）"}
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    with (HERE / "blacklist_sample.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["網站名稱", "網址", "件數"])
        for domain in BLACKLIST:
            writer.writerow(["範例假網站", f"https://{domain}", 1])

    with (HERE / "licensed_sample.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["名稱"])
        for name in LICENSED:
            writer.writerow([name])

    print(f"已產生：訓練 {len(SCAM) + len(NORMAL)} 筆、案例 {len(CASES)} 筆、黑名單 {len(BLACKLIST)} 筆")


if __name__ == "__main__":
    main()
